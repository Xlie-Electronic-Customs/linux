static int ov16a1q_init_controls(struct ov16a1q_device *sensor)
{
	struct v4l2_ctrl_handler *hdl = &sensor->ctrl_handler;

	v4l2_ctrl_handler_init(hdl, 4);
	sensor->sd.ctrl_handler = hdl;

	sensor->ctrls.exposure =
		v4l2_ctrl_new_std(hdl, &ov16a1q_ctrl_ops, V4L2_CID_EXPOSURE,
				  0, OV16A1Q_EXPOSURE_MAX, 1,
				  OV16A1Q_EXPOSURE_DEFAULT);
	sensor->ctrls.gain =
		v4l2_ctrl_new_std(hdl, &ov16a1q_ctrl_ops, V4L2_CID_ANALOGUE_GAIN,
				  0, OV16A1Q_GAIN_MAX, 1, OV16A1Q_GAIN_DEFAULT);
	sensor->ctrls.link_freq =
		v4l2_ctrl_new_int_menu(hdl, NULL, V4L2_CID_LINK_FREQ, 0, 0,
				       link_freq_menu_items);
	sensor->ctrls.pixel_rate =
		v4l2_ctrl_new_std(hdl, NULL, V4L2_CID_PIXEL_RATE, 0,
				  OV16A1Q_PIXEL_RATE, 1, OV16A1Q_PIXEL_RATE);

	if (hdl->error)
		return hdl->error;

	sensor->ctrls.link_freq->flags |= V4L2_CTRL_FLAG_READ_ONLY;
	sensor->ctrls.pixel_rate->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	return 0;
}

static int ov16a1q_check_hwcfg(struct device *dev)
{
	struct v4l2_fwnode_endpoint bus_cfg = {
		.bus_type = V4L2_MBUS_CSI2_DPHY,
	};
	struct fwnode_handle *ep;
	unsigned long link_freq_bitmap;
	int ret;

	ep = fwnode_graph_get_endpoint_by_id(dev_fwnode(dev), 0, 0, 0);
	if (!ep)
		return dev_err_probe(dev, -EPROBE_DEFER,
				     "waiting for fwnode graph endpoint\n");

	ret = v4l2_fwnode_endpoint_alloc_parse(ep, &bus_cfg);
	fwnode_handle_put(ep);
	if (ret)
		return dev_err_probe(dev, ret, "parsing endpoint failed\n");

	ret = v4l2_link_freq_to_bitmap(dev, bus_cfg.link_frequencies,
				       bus_cfg.nr_of_link_frequencies,
				       link_freq_menu_items,
				       ARRAY_SIZE(link_freq_menu_items),
				       &link_freq_bitmap);

	if (ret == 0 && bus_cfg.bus.mipi_csi2.num_data_lanes != 4)
		ret = dev_err_probe(dev, -EINVAL,
				    "number of CSI2 data lanes %u is not supported\n",
				    bus_cfg.bus.mipi_csi2.num_data_lanes);

	v4l2_fwnode_endpoint_free(&bus_cfg);
	return ret;
}

static int ov16a1q_probe(struct i2c_client *client)
{
	struct ov16a1q_device *sensor;
	unsigned long freq;
	u64 id = 0;
	int ret;

	ret = ov16a1q_check_hwcfg(&client->dev);
	if (ret)
		return ret;

	sensor = devm_kzalloc(&client->dev, sizeof(*sensor), GFP_KERNEL);
	if (!sensor)
		return -ENOMEM;

	sensor->clk = devm_v4l2_sensor_clk_get(&client->dev, NULL);
	if (IS_ERR(sensor->clk))
		return dev_err_probe(&client->dev, PTR_ERR(sensor->clk),
				     "failed to get clock\n");

	freq = clk_get_rate(sensor->clk);
	if (freq != OV16A1Q_MCLK_FREQ)
		return dev_err_probe(&client->dev, -EINVAL,
				     "external clock %lu is not supported\n", freq);

	sensor->reset = devm_gpiod_get(&client->dev, "reset", GPIOD_OUT_HIGH);
	if (IS_ERR(sensor->reset))
		return dev_err_probe(&client->dev, PTR_ERR(sensor->reset),
				     "getting reset GPIO\n");

	sensor->supplies[0].supply = "vana";
	sensor->supplies[1].supply = "vio";
	sensor->supplies[2].supply = "vdig";
	ret = devm_regulator_bulk_get(&client->dev, ARRAY_SIZE(sensor->supplies),
				      sensor->supplies);
	if (ret)
		return dev_err_probe(&client->dev, ret,
				     "getting regulators failed\n");

	v4l2_i2c_subdev_init(&sensor->sd, client, &ov16a1q_ops);
	sensor->sd.internal_ops = &ov16a1q_internal_ops;
	sensor->sd.flags |= V4L2_SUBDEV_FL_HAS_DEVNODE;

	sensor->regmap = devm_cci_regmap_init_i2c(client, 16);
	if (IS_ERR(sensor->regmap))
		return PTR_ERR(sensor->regmap);

	pm_runtime_set_active(&client->dev);
	pm_runtime_get_noresume(&client->dev);
	pm_runtime_enable(&client->dev);

	ret = ov16a1q_power_on(&client->dev);
	if (ret)
		goto err_pm;

	cci_read(sensor->regmap, OV16A1Q_REG_CHIP_ID, &id, &ret);
	if (ret)
		goto err_power_off;

	if ((id & 0xffff) != OV16A1Q_ID) {
		dev_err(&client->dev, "sensor ID error, read 0x%llx, expected 0x%x\n",
			id, OV16A1Q_ID);
		ret = -ENODEV;
		goto err_power_off;
	}

	dev_info(&client->dev, "detected OV16A1Q (id 0x%llx)\n", id);

	ret = ov16a1q_init_controls(sensor);
	if (ret)
		goto err_power_off;

	sensor->sd.entity.function = MEDIA_ENT_F_CAM_SENSOR;
	sensor->pad.flags = MEDIA_PAD_FL_SOURCE;
	ret = media_entity_pads_init(&sensor->sd.entity, 1, &sensor->pad);
	if (ret)
		goto err_free_ctrls;

	ret = v4l2_subdev_init_finalize(&sensor->sd);
	if (ret)
		goto err_entity;

	ret = v4l2_async_register_subdev_sensor(&sensor->sd);
	if (ret)
		goto err_subdev;

	pm_runtime_set_suspended(&client->dev);
	pm_runtime_put(&client->dev);

	return 0;

err_subdev:
	v4l2_subdev_cleanup(&sensor->sd);
err_entity:
	media_entity_cleanup(&sensor->sd.entity);
err_free_ctrls:
	v4l2_ctrl_handler_free(&sensor->ctrl_handler);
err_power_off:
	ov16a1q_power_off(&client->dev);
err_pm:
	pm_runtime_disable(&client->dev);
	pm_runtime_put_noidle(&client->dev);
	return ret;
}

static void ov16a1q_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct ov16a1q_device *sensor = to_ov16a1q_sensor(sd);

	v4l2_async_unregister_subdev(sd);
	v4l2_subdev_cleanup(sd);
	media_entity_cleanup(&sensor->sd.entity);
	v4l2_ctrl_handler_free(&sensor->ctrl_handler);
	pm_runtime_disable(&client->dev);
	if (!pm_runtime_status_suspended(&client->dev)) {
		ov16a1q_power_off(&client->dev);
		pm_runtime_set_suspended(&client->dev);
	}
}

static int ov16a1q_runtime_resume(struct device *dev)
{
	return ov16a1q_power_on(dev);
}

static int ov16a1q_runtime_suspend(struct device *dev)
{
	ov16a1q_power_off(dev);
	return 0;
}

